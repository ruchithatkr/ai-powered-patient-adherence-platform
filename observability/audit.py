"""Append-only, hash-chained audit store (optionally durable as JSONL). PHI-safe by construction.

Agents get append() only; there is no update/delete API. A single writer process is assumed
(hash chain); use a real audit database for multi-writer deployments.
"""

import hashlib
import json
import os
import threading
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from guardrails.checks import contains_sensitive

# Standard fields every event carries (CLAUDE.md section 15). Missing ones are stored as null / zero.
STANDARD_FIELDS: dict[str, Any] = {
    "span_id": None,
    "parent_span_id": None,
    "request_id": None,
    "workflow_version": None,
    "agent": None,
    "agent_version": None,
    "skill": None,
    "model": None,
    "prompt_version": "none (no LLM in decision path)",
    "tool": None,
    "tool_operation": None,
    "input_schema_hash": None,
    "evidence_ids": [],
    "policy_version": None,
    "guardrail_decision": None,
    "approval_id": None,
    "error_code": None,
    "latency_ms": None,
    "input_tokens": 0,
    "output_tokens": 0,
    "estimated_cost": 0.0,
    "action_receipt": None,
}
FORBIDDEN_KEYS = {
    "prompt", "patient_text", "token", "access_token", "name", "email", "phone", "body", "message", "text",
    "content", "free_text", "address", "dob", "ssn", "password", "secret", "api_key", "authorization", "first_name",
}  # fmt: skip


# Structural identifiers/hashes generated by this system (never patient text); exempt from value scrubbing, which could
# otherwise mangle e.g. an all-digit span id that resembles a phone number.
STRUCTURAL_KEYS = {
    "span_id", "parent_span_id", "request_id", "approval_id", "action_receipt", "started_at", "workflow_version",
    "policy_version", "agent_version", "input_schema_hash", "alert_key", "subject_hash",
}  # fmt: skip


class AuditIntegrityError(RuntimeError):
    pass


def h(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()[:16]


def _sanitize(value: Any) -> Any:
    if isinstance(value, str):
        kind = contains_sensitive(value)
        return f"[REDACTED:{kind}]" if kind else value
    if isinstance(value, list):
        return [_sanitize(v) for v in value]
    if isinstance(value, dict):
        return {k: _sanitize(v) for k, v in value.items()}
    return value


class AuditStore:
    def __init__(self, path: Path | None = None) -> None:
        self._events: list[dict[str, Any]] = []
        self._lock = threading.Lock()
        self._path = path
        self._prev = "GENESIS"
        self._verified_upto = 0
        if path is not None:
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.exists():
                self._events = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
                if not self.verify_chain():
                    raise AuditIntegrityError(f"audit log {path} failed hash-chain verification; refusing to start")
                self._prev = self._events[-1]["hash"] if self._events else "GENESIS"

    def append(
        self,
        *,
        trace_id: str,
        actor: str,
        node: str,
        status: str = "OK",
        input: Any = None,
        output: Any = None,
        timestamp: datetime | None = None,
        **fields: Any,
    ) -> str:
        bad = FORBIDDEN_KEYS & set(fields)
        if bad:
            raise ValueError(f"PHI-unsafe audit fields refused: {sorted(bad)}")
        with self._lock:
            span_id = fields.pop("span_id", None) or uuid.uuid4().hex[:16]
            ev: dict[str, Any] = {
                "timestamp": (timestamp or datetime.now(UTC)).isoformat(),
                "trace_id": trace_id,
                "actor": actor,
                "node": node,
                "status": status,
                "input_hash": h(input) if input is not None else None,
                "output_hash": h(output) if output is not None else None,
            }
            structural = {k: v for k, v in fields.items() if k in STRUCTURAL_KEYS}
            ev.update(
                {
                    **STANDARD_FIELDS,
                    **_sanitize({k: v for k, v in fields.items() if k not in STRUCTURAL_KEYS}),
                    **structural,
                    "span_id": span_id,
                }
            )
            ev["evidence_ids"] = list(ev["evidence_ids"] or [])
            ev["event_id"] = span_id
            ev["prev_hash"] = self._prev
            ev["hash"] = h(ev)
            self._prev = ev["hash"]
            self._events.append(ev)
            if self._path is not None:
                with self._path.open("a") as f:
                    f.write(json.dumps(ev, default=str) + "\n")
                    f.flush()
                    os.fsync(f.fileno())
            return span_id

    # -- reads -------------------------------------------------------------------
    def trace(self, trace_id: str) -> list[dict[str, Any]]:
        return sorted((e for e in self._events if e["trace_id"] == trace_id), key=lambda e: e.get("started_at") or e["timestamp"])

    def all(self) -> list[dict[str, Any]]:
        return list(self._events)

    def __len__(self) -> int:
        return len(self._events)

    def verify_chain(self, incremental: bool = False) -> bool:
        start = self._verified_upto if incremental else 0
        prev = self._events[start - 1]["hash"] if start else "GENESIS"
        for e in self._events[start:]:
            body = {k: v for k, v in e.items() if k != "hash"}
            if e["prev_hash"] != prev or h(body) != e["hash"]:
                return False
            prev = e["hash"]
        self._verified_upto = len(self._events)
        return True

    def export_redacted(self, trace_id: str) -> list[dict[str, Any]]:
        return [{k: v for k, v in e.items() if k != "prev_hash"} for e in self.trace(trace_id)]

    def gaps(self, trace_id: str) -> list[str]:
        """Missing trace nodes for a trace, derived from the manifest the workflow itself recorded."""
        events = self.trace(trace_id)
        if not events:
            return ["request"]
        nodes = {e["node"] for e in events}
        missing = [n for n in ("request", "agent_plan") if n not in nodes]
        manifest = next((e["stages_visited"] for e in reversed(events) if e.get("stages_visited")), None)
        if manifest is None:
            return missing + ["closing-event"]
        missing += [f"stage:{s}" for s in manifest if s not in ("approval", "close") and f"stage:{s}" not in nodes]
        if "approval_requested" not in nodes and "final" not in nodes:
            missing.append("final")
        return missing

    def open_traces(self) -> list[str]:
        return list(dict.fromkeys(e["trace_id"] for e in self._events if e["node"] == "request"))


CHAIN = [
    ("User Request", lambda e: e["node"] == "request"),
    ("Agent Plan", lambda e: e["node"] == "agent_plan"),
    ("Supervisor/Sub-agent", lambda e: e["node"].startswith("subagent:")),
    ("Skill", lambda e: e["node"].startswith("skill:")),
    ("Tool/MCP", lambda e: e["node"].startswith("tool:")),
    ("Evidence/Data", lambda e: bool(e.get("evidence_ids"))),
    ("Action", lambda e: bool(e.get("action_receipt"))),
    ("Guardrail Check", lambda e: bool(e.get("guardrail_decision"))),
    ("Human Approval", lambda e: e["node"] == "approval" and e["status"] in ("APPROVE", "REJECT", "OK")),
    ("Final Output", lambda e: e["node"] == "final"),
]  # fmt: skip


def chain_coverage(events: list[dict[str, Any]]) -> dict[str, bool]:
    """Which links of the required traceability chain are present in this trace (section 16)."""
    return {name: any(pred(e) for e in events) for name, pred in CHAIN}
